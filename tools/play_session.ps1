# Starts Assassin's Creed Brotherhood (ACBSP.exe) and waits until the user quits it.
# Run through the shared queue (profiles assassins-creed-brotherhood/*), not by hand.
#
# -Patched installs the current build\ACBRawMouseFix.asi, a generated
# acb-raw-mouse-fix.ini and the pinned Ultimate ASI Loader x86 (dinput8.dll) into the
# game folder for this session only, and removes them afterwards. The plugin's log is
# kept in research\runs\<time>-<name>\. Without -Patched any leftover plugin files are
# removed first, so the game runs stock.
#
# The game is started through Ubisoft Connect (uplay://launch/<id>/0, the id from the
# registry), so Connect starts ACBSP.exe once. Started directly (-Launch exe, or no
# Connect id), ACBSP.exe exits again while Connect logs in and relaunches it, sometimes
# only after a login or an update. So this waits for any ACBSP.exe, and treats a process
# that lived less than HandOffSec as that hand-off: the session isn't over until the real
# game has run and closed. (2026-11-03: a hand-off slower than the old 20 s grace ended
# the session early, removed the plugin, and the user played stock.)
param(
    [string]$GameDir = "D:\Program Files\Games\Ubisoft\Assassin's Creed Brotherhood",
    [int]$Minutes = 180,
    [string]$Arguments = '',
    [ValidateSet('connect', 'exe')]
    [string]$Launch = 'connect',
    [int]$StartGraceSec = 300,
    [int]$RelaunchGraceSec = 20,
    [int]$HandOffSec = 60,
    [switch]$Patched,
    [switch]$Stock,
    [double]$MouseScale = 25,
    [double]$Sensitivity = 1,
    [double]$SensitivityX = 1,
    [double]$SensitivityY = 1,
    [switch]$Watch,
    [int]$WatchSeconds = 30,
    [int]$FrameLimit = 0,
    [string]$Name = 'play'
)

$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot
$exe = Join-Path $GameDir 'ACBSP.exe'
$loaderSource = Join-Path $repo 'research\thirdparty\ual-x86-v9.7.4\dinput8.dll'
$loaderSha256 = 'D5A059AA467A7A7127C8F6169F79FA63FF0F55986EE9EB2FD9A281BEBF2AA2E6'
$pluginSource = Join-Path $repo 'build\ACBRawMouseFix.asi'
$gamePlugin = Join-Path $GameDir 'ACBRawMouseFix.asi'
$gameIni = Join-Path $GameDir 'acb-raw-mouse-fix.ini'
$gameLog = Join-Path $GameDir 'acb-raw-mouse-fix.log'
$gameLoader = Join-Path $GameDir 'dinput8.dll'

if (-not (Test-Path -LiteralPath $exe)) { Write-Host "not found: $exe"; exit 2 }

function Get-Game { @(Get-Process -Name 'ACBSP' -ErrorAction SilentlyContinue) }
function Get-Sha256([string]$Path) { (Get-FileHash -LiteralPath $Path -Algorithm SHA256).Hash }

# Removes only files this script installs; a dinput8.dll is removed only if it is the pinned loader.
function Remove-PluginFiles([string]$KeepLogIn) {
    foreach ($f in @($gamePlugin, $gameIni)) {
        if (Test-Path -LiteralPath $f) { Remove-Item -LiteralPath $f -Force; Write-Host "removed $f" }
    }
    if (Test-Path -LiteralPath $gameLoader) {
        if ((Get-Sha256 $gameLoader) -eq $loaderSha256) {
            Remove-Item -LiteralPath $gameLoader -Force; Write-Host "removed $gameLoader"
        } else {
            Write-Host "kept $gameLoader (not the pinned Ultimate ASI Loader; not installed by this script)"
        }
    }
    if (Test-Path -LiteralPath $gameLog) {
        if ($KeepLogIn) { Move-Item -LiteralPath $gameLog -Destination $KeepLogIn -Force }
        else { Remove-Item -LiteralPath $gameLog -Force }
    }
}

if ((Get-Game).Count -gt 0) {
    Write-Host 'ACBSP.exe is already running (started outside the queue). Quit it and run again.'
    exit 3
}

$runDir = $null
if ($Patched) {
    if (-not (Test-Path -LiteralPath $pluginSource)) { Write-Host "not built: $pluginSource (run build-msvc.cmd)"; exit 2 }
    if ((Get-Sha256 $loaderSource) -ne $loaderSha256) { Write-Host "loader hash mismatch: $loaderSource"; exit 2 }
    if ((Test-Path -LiteralPath $gameLoader) -and (Get-Sha256 $gameLoader) -ne $loaderSha256) {
        Write-Host "$gameLoader exists and is not the pinned loader: not overwriting it."
        exit 2
    }
    $runDir = Join-Path $repo ("research\runs\{0}-{1}" -f (Get-Date -Format 'yyyyMMdd-HHmmss'), ($Name -replace '[^\w.-]', '_'))
    New-Item -ItemType Directory -Force -Path $runDir | Out-Null

    $ini = @(
        '; generated by tools\play_session.ps1 for this session',
        '[Mouse]',
        "LinearCamera=$([int](-not $Stock))",
        ("MouseScale={0}" -f $MouseScale.ToString([System.Globalization.CultureInfo]::InvariantCulture)),
        ("Sensitivity={0}" -f $Sensitivity.ToString([System.Globalization.CultureInfo]::InvariantCulture)),
        ("SensitivityX={0}" -f $SensitivityX.ToString([System.Globalization.CultureInfo]::InvariantCulture)),
        ("SensitivityY={0}" -f $SensitivityY.ToString([System.Globalization.CultureInfo]::InvariantCulture)),
        'UseRawInput=1',
        "RemoveClamp=$([int](-not $Stock))",
        '[Diagnostics]',
        'StatsLog=1', 'RawSniff=1', 'FrameStats=0',
        "FrameLimit=$FrameLimit",
        "WatchRightStick=$([int][bool]$Watch)",
        "WatchSeconds=$WatchSeconds"
    )
    Remove-PluginFiles ''
    Copy-Item -LiteralPath $pluginSource -Destination $gamePlugin
    Copy-Item -LiteralPath $loaderSource -Destination $gameLoader
    Set-Content -LiteralPath $gameIni -Value $ini -Encoding Ascii
    Copy-Item -LiteralPath $gameIni -Destination $runDir
    $pluginHash = Get-Sha256 $gamePlugin
    Set-Content -LiteralPath (Join-Path $runDir 'session.txt') -Encoding Ascii -Value @(
        "started $(Get-Date -Format s)", "plugin sha256 $pluginHash", "loader sha256 $loaderSha256",
        "Stock=$([bool]$Stock) MouseScale=$MouseScale Sensitivity=$Sensitivity X=$SensitivityX Y=$SensitivityY Watch=$([bool]$Watch) WatchSeconds=$WatchSeconds FrameLimit=$FrameLimit Minutes=$Minutes")
    Write-Host "installed the plugin (sha256 $($pluginHash.Substring(0, 16))...), loader and ini; run folder $runDir"
} else {
    Remove-PluginFiles ''
}

$exitCode = 0
try {
    $started = Get-Date
    $deadline = $started.AddMinutes($Minutes)
    $connectId = $null
    if ($Launch -eq 'connect' -and -not $Arguments) {
        $installs = 'HKLM:\SOFTWARE\WOW6432Node\Ubisoft\Launcher\Installs'
        $wanted = [System.IO.Path]::GetFullPath($GameDir).TrimEnd('\')
        foreach ($install in @(Get-ChildItem $installs -ErrorAction SilentlyContinue)) {
            $dir = (Get-ItemProperty $install.PSPath -ErrorAction SilentlyContinue).InstallDir
            if ($dir -and [System.IO.Path]::GetFullPath($dir).TrimEnd('\') -ieq $wanted) { $connectId = $install.PSChildName }
        }
    }
    $launcher = $null
    if ($connectId) {
        Write-Host "[$($started.ToString('HH:mm:ss'))] starting the game through Ubisoft Connect (uplay://launch/$connectId/0, limit $Minutes min)"
        Start-Process "uplay://launch/$connectId/0"
    } else {
        Write-Host "[$($started.ToString('HH:mm:ss'))] starting $exe $Arguments (limit $Minutes min)"
        $sp = @{ FilePath = $exe; WorkingDirectory = $GameDir; PassThru = $true }
        if ($Arguments) { $sp.ArgumentList = $Arguments }
        $launcher = Start-Process @sp
        Write-Host "launched pid $($launcher.Id)"
    }

    # Wait for the game to be up (Ubisoft Connect may need to start and log in first), and
    # until it has run and closed. A process shorter than HandOffSec is Connect's hand-off.
    $seenPids = @{}
    $lastSeen = $null
    $longestLife = 0
    while ($true) {
        $now = Get-Date
        $procs = Get-Game
        foreach ($p in $procs) {
            if (-not $seenPids.ContainsKey($p.Id)) {
                $seenPids[$p.Id] = $now
                Write-Host "[$($now.ToString('HH:mm:ss'))] ACBSP.exe running, pid $($p.Id)"
            }
            $life = ($now - $seenPids[$p.Id]).TotalSeconds
            if ($life -gt $longestLife) { $longestLife = $life }
        }
        if ($procs.Count -gt 0) {
            $lastSeen = $now
        } elseif ($null -eq $lastSeen) {
            if (($now - $started).TotalSeconds -gt $StartGraceSec) {
                Write-Host "the game did not start within $StartGraceSec s (Ubisoft Connect login or an error dialog?)"
                $exitCode = 4
                break
            }
        } else {
            $gone = ($now - $lastSeen).TotalSeconds
            if ($longestLife -ge $HandOffSec) {
                if ($gone -gt $RelaunchGraceSec) { break }
            } elseif ($gone -gt $StartGraceSec) {
                Write-Host ("the game exited after {0:0} s and was not started again within $StartGraceSec s" -f $longestLife)
                break
            }
        }
        if ($now -gt $deadline) {
            Write-Host "session limit of $Minutes min reached: closing the game"
            Get-Game | ForEach-Object { try { $_.Kill() } catch {} }
            Start-Sleep -Seconds 2
            $exitCode = 5
            break
        }
        Start-Sleep -Seconds 1
    }

    $played = (Get-Date) - $started
    $code = $null
    try { if ($launcher -and $launcher.HasExited) { $code = $launcher.ExitCode } } catch {}
    Write-Host ("[{0}] game closed after {1:hh\:mm\:ss} (pids seen: {2}; first process exit code: {3})" -f `
        (Get-Date).ToString('HH:mm:ss'), $played, (($seenPids.Keys | Sort-Object) -join ', '), $code)
} finally {
    if ($Patched) {
        if (Test-Path -LiteralPath $gameIni) {
            Copy-Item -LiteralPath $gameIni -Destination (Join-Path $runDir 'acb-raw-mouse-fix.final.ini') -Force
        }
        Remove-PluginFiles $runDir
        $log = Join-Path $runDir 'acb-raw-mouse-fix.log'
        if (Test-Path -LiteralPath $log) {
            $lines = Get-Content -LiteralPath $log
            Write-Host "---- plugin log: $log ($($lines.Count) lines)"
            if (-not ($lines -match 'd3d9: device created')) {
                Write-Host 'WARNING: the plugin never saw the game create its device: the game you played may have run without it.'
                if ($exitCode -eq 0) { $exitCode = 7 }
            }
            $lines | Where-Object { $_ -match 'host:|signature|hook|d3d9:|raw: (registration|subclass|no raw|the mouse)|watch: (window|slot)|config:|Sensitivity |F8:|first-person' } |
                Select-Object -First 40 | ForEach-Object { Write-Host $_ }
            Write-Host '---- last statistics'
            $lines | Where-Object { $_ -match 'mouse map:|camera:|raw: [0-9(]|frames:' } | Select-Object -Last 12 | ForEach-Object { Write-Host $_ }
            $summary = @($lines | Where-Object { $_ -match 'watch summary' })
            if ($summary.Count -gt 0) {
                Write-Host "---- right-stick readers ($($summary.Count))"
                $summary | Select-Object -First 30 | ForEach-Object { Write-Host $_ }
            }
        } else {
            Write-Host 'no plugin log: the loader did not load the plugin (check dinput8.dll loading)'
            if ($exitCode -eq 0) { $exitCode = 6 }
        }
    }
}
exit $exitCode
